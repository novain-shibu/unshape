"""Re-derive every published number from the raw logs (no hand-typed numbers in the report).

Inputs : logs/v3_20261016-184238.json (synthetic, final pipeline), logs/v3_20261016-184820.json (real, final pipeline),
         logs/ocr_scores.json (fair-normalised comparison incl. free Tesseract OCR).
Outputs: results/summary.json, results/RESULTS.md
"""
import json, random
from pathlib import Path

BASE = "../results"
SYN = f"{BASE}/logs/v3_20261016-184238.json"
REAL = f"{BASE}/logs/v3_20261016-184820.json"
OCR = f"{BASE}/logs/ocr_scores.json"


def load(p):
    return json.load(open(p, encoding="utf-8"))


def pooled(rows):
    w = sum(r["ml_words"] for r in rows)
    v = sum(round(r["ml_words"] * r["self_verified"]) for r in rows)
    return v, w


def boot_ci(rows, n=10000, seed=1):
    rnd = random.Random(seed)
    stats = []
    for _ in range(n):
        s = [rnd.choice(rows) for _ in rows]
        v, w = pooled(s)
        stats.append(v / w)
    stats.sort()
    return stats[int(0.025 * n)], stats[int(0.975 * n)]


def main():
    syn, real, ocr = load(SYN), load(REAL), load(OCR)
    groups = {
        "gazette_word2019": [r for r in real if r["pdf"].startswith("prs_") and r["pdf"] != "prs_11.pdf"],
        "print_to_pdf": [r for r in real if r["pdf"].startswith(("air_", "ku_"))],
        "libreoffice": [r for r in real if r["pdf"] == "prs_11.pdf"],
        "unseen_wkhtmltopdf_frozen_catalogue": [r for r in real if r["pdf"].startswith("lsg_")],
    }
    out = {"synthetic": {}, "real_groups": {}, "ocr_real_overlap": {}}
    for name, r in ocr.items():
        if name.startswith("wiki"):
            out["synthetic"][name] = {k: r[k] for k in r if k.endswith(("word_recall", "cer")) or k == "ocr_sec_per_page"}
    for g, rows in groups.items():
        v, w = pooled(rows)
        d = {"pdfs": len(rows), "malayalam_words": w, "rendering_verified": v, "share": round(v / max(1, w), 4),
             "per_pdf": {r["pdf"]: r["self_verified"] for r in rows},
             "pdfs_at_or_above_95pct": sum(r["self_verified"] >= 0.95 for r in rows)}
        if len(rows) >= 5 and w:
            lo, hi = boot_ci(rows)
            d["share_95ci_bootstrap_over_pdfs"] = [round(lo, 4), round(hi, 4)]
        out["real_groups"][g] = d
    for name, r in ocr.items():
        if not name.startswith("wiki"):
            out["ocr_real_overlap"][name] = {k: r[k] for k in ("pages", "verified_words", "ocr_has_ours", "pymupdf_has_ours")}
    Path(BASE).mkdir(exist_ok=True)
    Path(f"{BASE}/summary.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")

    L = ["# Results (generated by make_results.py from logs/; do not edit by hand)", "",
         "## 1. Synthetic PDFs with known text (Malayalam Wikipedia, Nirmala UI; Word 365 and Edge/Chromium)",
         "Exact-word recall (higher is better) / character error rate. Fair normalisation: NFC, joiners removed, old ZWJ chillus",
         "mapped to atomic chillus, punctuation and digits removed.", "",
         "| PDF | Unshape | Tesseract OCR (free) | PyMuPDF | pdfminer |", "|---|---|---|---|---|"]
    for n, r in sorted(out["synthetic"].items()):
        L.append(f"| {n} | {r['unshape_word_recall']:.1%} / {r['unshape_cer']:.2%} | {r['ocr_word_recall']:.1%} / {r['ocr_cer']:.2%} "
                 f"| {r['pymupdf_word_recall']:.1%} / {r['pymupdf_cer']:.2%} | {r['pdfminer_word_recall']:.1%} / {r['pdfminer_cer']:.2%} |")
    L += ["", "## 2. Real public PDFs: share of Malayalam words that are rendering-verified (no ground truth needed)", "",
          "| Group | PDFs | Malayalam words | Verified | Share | 95% CI (bootstrap over PDFs) | PDFs >= 95% |", "|---|---|---|---|---|---|---|"]
    for g, d in out["real_groups"].items():
        ci = d.get("share_95ci_bootstrap_over_pdfs")
        L.append(f"| {g} | {d['pdfs']} | {d['malayalam_words']} | {d['rendering_verified']} | {d['share']:.1%} | "
                 f"{f'{ci[0]:.1%}-{ci[1]:.1%}' if ci else 'n/a'} | {d['pdfs_at_or_above_95pct']}/{d['pdfs']} |")
    L += ["", "## 3. Real PDFs: do other tools also produce the words we verified? (OCR'd pages only, max 15 per PDF)", "",
          "| PDF | pages | verified words | in Tesseract output | in PyMuPDF output |", "|---|---|---|---|---|"]
    for n, r in sorted(out["ocr_real_overlap"].items()):
        L.append(f"| {n} | {r['pages']} | {r['verified_words']} | {r['ocr_has_ours']:.1%} | {r['pymupdf_has_ours']:.1%} |")
    Path(f"{BASE}/RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
